/**
 * 어종 도감 — 생김새 형질과 생태.
 * 
 * **규제(`fish_regulation`)와 열쇠를 공유한다.** 규제 항목 하나에 도감 하나가 붙는다.
 * 참문어/대문어처럼 한 `FishSpecies` 가 두 항목으로 나뉜 경우에도 각각 따로 붙는다.
 * 
 * 형질은 **닮은 종과 가르는 데 실제로 쓰이는 것만** 담았다. 자료마다 값이 갈리는
 * 형질(부시리의 노란 띠, 말쥐치의 지느러미 위치 등)은 일부러 뺐다 — 애매한 근거로
 * "이렇게 생겼다"고 단정하면 사용자가 잘못된 물고기를 가져간다.
 * 
 * 생태도 마찬가지다. 산란기·수심은 기관마다 값이 달라, 갈리는 경우 폭을 넓히거나
 * "자료마다 갈린다"를 그대로 적었다.
 */

export interface FishTrait {
  /** 한 줄로 끊어 읽는 형질. 목록에 굵게 뜬다. */
  head: string;
  /** 왜 그런지, 닮은 종과 어떻게 다른지. 없을 수 있다. */
  detail?: string;
}

export interface FishProfile {
  /** 규제 항목의 key 와 같다. */
  key: string;
  scientificName: string;
  family: string;
  /** 표준명이 화면 이름과 다를 때만 (예: 가오리 → 참홍어). */
  nameNote?: string;
  /** 생김새로 가리는 법. */
  traits: FishTrait[];
  habitat?: string;
  food?: string;
  season?: string;
  tip?: string;
  /** 닮은 종 한 줄 경고. */
  lookalike?: string;
  sources: string[];
}

